// 변수를 "무엇으로 재야 하는가"로 분류한다.
//
// 왜 접미사인가:
// 사용자가 칠 수 있는 변수는 무한하다(카페인 섭취량, 걸음 수, 저축액,
// 배달 주문 횟수, 교재비, 게임 플레이 시간 ...). 변수 하나하나를 목록에
// 올리는 방식은 목록에 없는 27번째 변수에서 그대로 무너진다. 오늘 고친
// 버그 여섯 건이 전부 그 모양이었다.
//
// 반면 한국어 측정 명사의 **접미사**는 닫힌 집합이다. "카페인 섭취량"을
// 몰라도 "량"으로 끝나니 수량이라는 것은 안다. 그래서 개별 변수가 아니라
// 접미사로 분류한다. 새 변수가 들어와도 접미사만 걸리면 제대로 묻는다.
//
// 그리고 구간을 지어내지 않는다. 구간을 정하려면 단위·범위·구간폭 세 가지를
// 알아야 하고, 범위는 응답자 집단에 따라 달라진다(월 생활비: 대학생 30~80만원
// vs 직장인 100~300만원). 변수명만으로는 결정할 수 없으므로, 구간을 모르는
// 부류는 숫자를 직접 받는다. 구간보다 분석하기도 좋다.

export type SurveyVariableKind =
  /** 시간·기간. 구간이 집단과 무관하게 안정적이라 구간 선택으로 받는다. */
  | "duration"
  /** 횟수·빈도. 마찬가지로 구간이 안정적이다. */
  | "frequency"
  /** 수량·금액. 단위와 범위가 변수마다 달라 숫자를 직접 받는다. */
  | "amount"
  /** 점수·학점. 만점 기준이 달라 숫자를 직접 받는다. */
  | "score"
  /** 비율·퍼센트. 0~100이 자명하므로 숫자를 직접 받는다. */
  | "ratio"
  /** 만족도·자존감처럼 크기가 주관적인 구성 개념. 5점 척도가 원래 맞다. */
  | "attitude"
  /** 활용·이용·학습처럼 "하다"가 붙는 행위. 얼마나 자주 하는지를 묻는다. */
  | "activity"
  /** 종류·수단처럼 크기가 없는 범주. 척도를 붙이면 응답이 불가능하다. */
  | "category"
  /** 있음/없음. */
  | "binary"
  /** 위 어디에도 안 걸림. 지어내지 말고 이 상태를 그대로 알린다. */
  | "unknown";

type KindRule = { kind: SurveyVariableKind; pattern: RegExp };

// 순서가 중요하다. 좁은 규칙이 먼저 온다.
// "이용 빈도"는 frequency지, 뒤의 "도"를 보고 attitude가 되면 안 된다.
const kindRules: KindRule[] = [
  { kind: "binary", pattern: /(?:여부|유무)$/ },
  { kind: "frequency", pattern: /(?:빈도|횟수|회수|번수)$/ },
  { kind: "duration", pattern: /(?:시간|기간|시간대|분|초)$/ },
  // 률/율 표기가 둘 다 쓰인다(결식률, 참여율).
  { kind: "ratio", pattern: /(?:비율|비중|퍼센트|률|율)$/ },
  { kind: "score", pattern: /(?:학점|점수|평점|등급|성적|점)$/ },
  { kind: "amount", pattern: /(?:량|액|비|값|수|개수|건수|거리|무게|나이|연령)$/ },
  // "하다"가 붙는 행위 명사. 크기가 아니라 얼마나 자주 하는지를 물어야 한다.
  // "사교육 및 생성형 AI 활용은 어떻게 되나요?"처럼 속성을 묻는 형태로 나가면
  // 어색하다. 시간·빈도 규칙이 먼저 오므로 "이용 시간"·"이용 빈도"는 여기까지
  // 오지 않는다.
  {
    kind: "activity",
    pattern:
      /(?:활용|이용|사용|참여|실천|학습|복습|예습|실습|자습|연습|운동|독서|훈련|공부|관리|준비|점검)$/,
  },
  // 태도류는 접미사가 넓어서 뒤에 둔다. 위 규칙에 안 걸린 것만 온다.
  // "성"은 주체성·자율성·안전성처럼 정도를 가진 구성 개념을 만든다.
  // 여성·특성처럼 예외가 있으나 설문 변수로 단독으로 쓰이는 일은 드물다.
  {
    kind: "attitude",
    pattern:
      /(?:만족도|선호도|충성도|피로도|난이도|중요도|인지도|정도|수준|의향|의지|자신감|만족감|효능감|자존감|소속감|스트레스|부담|불안|우울|행복|태도|인식|의견|생각|평가|영향|관심|신뢰|공감|집중력|체력|이해력|적응력|역량|능력|질|성|의식|욕구|의욕|열의|사고|몰입|효능|리터러시|감수성)$/,
  },
  { kind: "category", pattern: /(?:형태|지역|수단|방식|유형|종류|경로|장소|위치|전공|학과|계열)$/ },
];

export function surveyVariableKind(name: string): SurveyVariableKind {
  const normalized = name.replace(/\s+/g, "").trim();
  if (!normalized) return "unknown";
  for (const rule of kindRules) {
    if (rule.pattern.test(normalized)) return rule.kind;
  }
  return "unknown";
}

/**
 * 숫자를 직접 받는 부류에 붙일 단위 힌트. 구간을 지어내는 대신 응답자가
 * 자기 값을 그대로 적게 한다. 예시는 형식을 알려주기 위한 것이지 범위를
 * 규정하지 않는다.
 */
export function numericAnswerHint(kind: SurveyVariableKind, name: string) {
  if (kind === "score") {
    return /학점|평점/.test(name)
      ? "숫자로 적어주세요. (예: 3.5)"
      : "숫자로 적어주세요. (예: 85)";
  }
  if (kind === "ratio") return "퍼센트로 적어주세요. (예: 30)";
  // amount는 단위가 변수마다 다르다(잔·권·보·원·kg). 단위를 함께 받는다.
  return "숫자와 단위를 함께 적어주세요. (예: 2잔, 3만원)";
}
