import {
  surveyRegressionCaseSchema,
  type SurveyRegressionCase,
} from "../v1/schema";

type Cluster =
  | "past_distortion"
  | "negation"
  | "multiple_purposes"
  | "multiple_targets"
  | "relationship"
  | "clarification"
  | "noisy";

type Fixture = {
  id: string;
  cluster: Cluster;
  input: string;
  target: string[];
  object: string[];
  purposes: string[];
  required: string[];
  quality?: "clear" | "noisy_recoverable" | "ambiguous";
  eligibility?: string[];
  contexts?: string[];
  negation?: boolean;
  screening?: boolean;
  terms?: string[];
  cardinality?: "single" | "multiple";
  outcome?: "survey" | "clarification";
  archetypes?: string[];
};

function fixture(input: Fixture): SurveyRegressionCase {
  const outcome = input.outcome ?? "survey";
  const quality = input.quality ?? "clear";
  return surveyRegressionCaseSchema.parse({
    id: input.id,
    split: "dev",
    stratum:
      outcome === "clarification"
        ? "clarification"
        : input.cluster === "past_distortion"
          ? "past_error_variant"
          : "complex_relation",
    category: `intent_v2_${input.cluster}`,
    difficulty: quality === "clear" ? "medium" : "hard",
    surveyMode: "standard",
    questionCount: 7,
    input: input.input,
    expectedOutcome: outcome,
    inputQuality: quality,
    expectedTargetPopulation: input.target,
    expectedEligibilityConditions: input.eligibility ?? [],
    contextEntities: input.contexts ?? [],
    screeningExpected: input.screening ?? false,
    expectedSurveyObject: input.object,
    expectedPurposeConcepts: input.purposes,
    requiredQuestionConcepts: input.required,
    forbiddenPurposeConcepts: [],
    mustPreserveTerms: input.terms ?? [],
    mustPreserveNegation: input.negation ?? false,
    forbiddenTargetExpansions: [],
    forbiddenSurveyObjects: [],
    forbiddenQuestionConcepts: [
      "generic filler",
      "요소 N",
      "핵심 경험 N",
      "선행 값",
      "결과 값",
      "변수 A",
      "변수 B",
    ],
    clarificationExpected: outcome === "clarification",
    expectedIntentModes:
      input.cardinality === "multiple" || input.purposes.length > 1
        ? ["composite"]
        : ["single"],
    expectedTargetCardinality: input.cardinality ?? "single",
    expectedArchetypes: input.archetypes ?? ["attitude"],
    tags: [
      ...(quality === "noisy_recoverable" ? ["noisy_input" as const] : []),
      ...(quality === "ambiguous" ? ["clarification" as const] : []),
      ...(input.negation ? ["negation" as const] : []),
      ...((input.eligibility?.length ?? 0) > 0 ? ["timeframe" as const] : []),
      ...(input.cardinality === "multiple" ? ["multiple_targets" as const] : []),
      ...(input.purposes.length > 1 && input.cardinality !== "multiple"
        ? ["single_target_multi_purpose" as const]
        : []),
      ...(/[가-힣]+(?:온|빛|별|숲|길|담|새|루)/u.test(input.input)
        ? ["virtual_entity" as const]
        : []),
      ...(/주민|직장인|고객|보호자|환자|자영업자|프리랜서/u.test(input.input)
        ? ["non_university" as const]
        : []),
    ],
    notes: `v1.2 canonical intent V2 architecture targeted: ${input.cluster}`,
  });
}

