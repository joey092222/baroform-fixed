// 조사 요청문에는 조사 대상이 아니라 "무엇을 할지"를 가리키는 메타 표현이
// 붙는다("학식 만족도 조사 결과 개선 방안"). 이걸 안 걷어내면 요청문 전체가
// 조사 대상이 되어 "학식 만족도 조사 결과 개선 방안에서의 식사 경험에
// 전반적으로 얼마나 만족하시나요?" 같은 문항이 나간다.
//
// 조사 대상은 두 경로로 따로 추출된다. survey-intent의 briefSubjectFromContent가
// researchSubject를, survey-semantic-intent의 normalizedObjectLabel이
// surveyObject를 만든다. 문항 본문에 실리는 것은 후자다. 한쪽만 고치면
// 제목만 깨끗해지고 문항은 그대로 깨진 채 나가므로 규칙을 여기 모아 둘 다
// 쓰게 한다.
//
// 변수명과 달리 연구 메타 어휘는 닫힌 집합이라 목록으로 다룰 수 있다.
// 순서는 중요하지 않다. stripSubjectTails가 수렴할 때까지 돌린다.
export const subjectTailStrips: RegExp[] = [
  // "조사"는 조사 행위일 수도, 조사 대상 명사의 일부일 수도 있다
  // ("학식 만족도 조사"의 조사 vs "사용자 조사"의 조사). 두 갈래로 나눈다.
  //
  // (a) "조사" 뒤에 다른 말이 이어지면 행위다. 조사 대상 명사 뒤에
  //     "결과 개선 방안" 같은 말이 붙는 일은 없다. 어절 경계를 요구해
  //     "여론조사 앱"처럼 명사 안에 든 "조사"는 건드리지 않는다.
  /(?:^|\s)(?:설문\s*)?(?:조사|연구)\s+.*$/,
  // (b) 맨 끝의 "조사"는 앞이 측정 차원일 때만 행위로 본다.
  //     "학식 만족도 조사"는 떼고 "사용자 조사"는 남긴다.
  /(?<=만족도|인식|인지도|현황|실태|경험|행태|패턴|빈도|의향|수요|선호|이용|사용|평가)\s*(?:설문\s*)?(?:조사|연구)$/,
  // 목적절: "~을 위한", "~를 통해", "~를 바탕으로"
  /\s*(?:을|를)?\s*(?:위한|위해|통한|통해|바탕으로|토대로|중심으로)(?:\s.*)?$/,
  // 조사 행위를 가리키는 서술 명사
  /\s*(?:실태|현황)?\s*(?:파악|분석|도출|수집|진단|점검|검토)$/,
  // 산출물
  /\s*(?:보고서|리포트|결과지)$/,
  // 측정 차원
  /\s+(?:인지도|인지|인식)\s*(?:과|와|및)\s*(?:사용|이용)\s*(?:경험|현황|행태|실태|패턴|빈도)$/,
  /\s+(?:이용|사용|참여|구매|방문|협업)\s*(?:현황|행태|실태|빈도|횟수|시간|경험|패턴|만족도|의향)(?:\s*(?:과|와|및)\s*.+)?$/,
  /\s+(?:만족도|불편\s*사항|개선점|갈등|협업\s*경험)(?:\s*(?:과|와|및)\s*.+)?$/,
  // "학식 실태 조사" → 조사를 뗀 뒤 남는 "실태". \s+를 요구해 "실태" 하나만
  // 남은 축약 입력은 비우지 않는다.
  /\s+(?:실태|현황)$/,
  // 뒤쪽 차원을 뗄 때 이어주던 접속조사가 남는다("동아리 활동 성과와").
  // "와"와 "및"만 뗀다. 한국어 명사는 "와"로 끝나는 일이 거의 없어 안전하다.
  // "과"는 학과·성과·효과처럼 명사의 일부인 경우가 많고 표면형으로 접속조사와
  // 구분되지 않는다("수업과 만족도" vs "학과 만족도"). 잘못 떼면 주제어가
  // "학"이 되므로 건드리지 않는다.
  /\s*(?:와|및)$/,
];

/**
 * 꼬리 규칙은 서로의 대상을 새로 노출시킨다. "학식 만족도 실태 파악을 위한
 * 조사"는 조사 → 위한 → 실태 파악 → 만족도 순으로 네 겹을 벗겨야 "학식"이
 * 남는다. 한 번만 훑으면 첫 겹만 떨어지므로 더 이상 줄지 않을 때까지 반복해
 * 규칙 순서에 대한 의존을 없앤다. 모든 규칙이 문자열을 짧게만 만들므로
 * 수렴하며, 상한은 안전핀이다. 전부 떨어져 비면 직전 상태를 돌려준다.
 */
// 연구 초록·설문 소개문의 상투구. 파서는 짧은 주제구("학식 만족도 조사")를
// 상정하는데, 사용자가 논문식 소개문을 통째로 붙여넣으면 그 전체를 하나의
// 조사 대상으로 압축하려다 조각이 남는다.
//
//   "본 설문조사는 '…학습자 주체성에 미치는 영향'을 분석하기 위한 학술 연구
//    목적으로 진행됩니다."  →  조사 대상 "학술"
//                          →  "학술을 직접 수행해 본 경험이 있나요?"
//
// 도입부와 목적절만 걷어내면 안쪽은 이미 파서가 다룰 수 있는 형태다.
// 위 예시는 걷어낸 뒤 변수 두 개(사교육 및 생성형 AI 활용 / 학습자 주체성)로
// 정확히 분해된다.
const abstractIntro =
  /^(?:본|이번|금번|이|저희)\s*(?:설문\s*조사|설문|조사|연구|리서치)(?:는|은|에서는|에서)\s*/;
// "~을 분석하기 위한", "~를 파악하기 위해", "~하고자 합니다"
const abstractPurposeClause =
  /\s*(?:을|를)?\s*(?:분석|파악|규명|확인|알아보|살펴보|검토|도출|모색|탐색|조사|연구)(?:하기|하고자|해|하려|하고)?\s*(?:위한|위해|위하여)?\s*[^.]*$/;
const abstractClosing =
  /\s*(?:입니다|합니다|됩니다|진행됩니다|실시됩니다)\s*[.]?\s*$/;

/**
 * 소개문처럼 "문장으로 쓰인" 입력일 때만 손댄다. 짧은 주제구는 도입부도
 * 서술형 종결어미도 없으므로 그대로 통과한다. 기존 테스트 프롬프트 193개
 * 가운데 이 게이트에 걸리는 것은 없었다.
 */
function looksLikeResearchAbstract(raw: string) {
  const trimmed = raw.trim();
  return (
    abstractIntro.test(trimmed) ||
    /(?:입니다|합니다|됩니다|하고자\s*합니다)\s*[.]?\s*$/.test(trimmed) ||
    /(?:입니다|합니다|됩니다)[.]/.test(trimmed)
  );
}

/**
 * 연구 초록에서 조사 주제만 남긴다. 소개문이 아니면 원문을 그대로 돌려준다.
 *
 * 인용부호 안이 있으면 그것을 우선한다. 논문식 소개문은 연구 주제를 따옴표로
 * 묶는 관례가 있어 신호가 강하다. normalizePrompt보다 먼저 도는 자리라
 * 따옴표가 아직 살아 있다.
 */
export function stripResearchAbstract(raw: string) {
  if (!looksLikeResearchAbstract(raw)) return raw;
  // 주제는 보통 첫 문장에 있다.
  const firstSentence = raw.split(/(?<=[.。])\s+/)[0] ?? raw;
  const quoted = firstSentence.match(
    /[‘'"“]([^’'"”]{6,60})[’'"”]/,
  )?.[1];
  if (quoted?.trim()) return quoted.trim();
  const core = firstSentence
    .replace(abstractIntro, "")
    .trim()
    .replace(abstractClosing, "")
    .trim()
    .replace(abstractPurposeClause, "")
    .trim();
  // 너무 많이 깎였으면 원문이 낫다.
  return core.length >= 4 ? core : raw;
}

/**
 * "개선이 필요한 부분", "부족한 점"의 "필요/부족"은 수요 신호가 아니다.
 * 관계절 안에 들어 있고 핵심어는 "부분"이며, 요청의 성격은 새로운 무언가를
 * 원한다가 아니라 기존 대상의 개선점 파악이다.
 *
 * 이걸 수요로 읽으면 "학식 ... 개선이 필요한 부분"이 "현재 생활권에 새로
 * 생기길 원하는 부분을 골라주세요"가 되어 주제가 통째로 바뀐다. 검증은
 * 통과하므로 사용자가 눈으로 보기 전까지 드러나지 않는다.
 *
 * 같은 판정이 세 곳에 필요하다. survey-context의 surveyArchetype,
 * survey-intent의 detectIntent, survey-semantic-intent의 decisionOption이
 * 각각 "필요"를 보고 라우팅한다. 하나만 고치면 나머지 둘이 되돌린다.
 */
export function isImprovementNeedClause(value: string) {
  return (
    /(?:개선|보완|수정|정비|변화|조치|지원|해결)\s*(?:이|가)?\s*필요/.test(value) ||
    /부족한\s*(?:부분|점|면)/.test(value)
  );
}

export function stripSubjectTails(value: string) {
  let current = value.replace(/\s+/g, " ").trim();
  for (let pass = 0; pass < 8; pass += 1) {
    const previous = current;
    for (const strip of subjectTailStrips) {
      current = current.replace(strip, "");
    }
    current = current.replace(/\s+/g, " ").trim();
    if (current === previous) break;
    if (!current) return previous;
  }
  return current;
}
